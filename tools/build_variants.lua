-- Builds loot_variants.lua: which tier set pieces are versions of the same
-- piece (quest upgrades / Turtle variants), so a member wearing any version
-- shows what they paid for the one that dropped.
-- Sources: Atlas-CFM's set pages (Sets.lua: one page per class and tier) and
-- DmorphOcto's per-slot item lists (Items.lua, ItemsExtra.lua).
-- Run from the AddOns folder with DmorphOcto's LuaHost:
--   DmorphOcto\tools\LuaHost\bin\LuaHost.exe shootyepgp\tools\build_variants.lua
local SETS = "Atlas-CFM/CFMLoot/Data/Tables/Sets.lua"
local SLOTFILES = { "DmorphOcto/Data/Items.lua", "DmorphOcto/Data/ItemsExtra.lua" }
local OUT = "shootyepgp/loot_variants.lua"
local SLOTNAME = { [1] = "head", [3] = "shoulder", [5] = "chest", [6] = "waist", [7] = "legs", [8] = "feet", [9] = "wrist", [10] = "hands", [15] = "back", [16] = "main hand", [17] = "off hand", [18] = "ranged" }

local slot = {}
for _, path in ipairs(SLOTFILES) do
  local cur
  for line in io.lines(path) do
    local _, _, s = string.find(line, "%[(%d+)%] = %[%[")
    if s then cur = tonumber(s)
    elseif string.find(line, "^%]%]") then cur = nil
    elseif cur then
      local _, _, id = string.find(line, "^(%d+)\t")
      if id then slot[tonumber(id)] = cur end
    end
  end
end

local pages, order, page = {}, {}, nil
for line in io.lines(SETS) do
  local _, _, p = string.find(line, "^%s*([%w_]+) = {%s*$")
  if p then
    page = { name = p, ids = {} }
    pages[p] = page
    table.insert(order, p)
  elseif page then
    local _, _, id, nm = string.find(line, "{ id = (%d+).-%-%-%s*(.-)%s*$")
    if id then table.insert(page.ids, { tonumber(id), nm }) end
  end
end

local out = { "-- Generated by tools/build_variants.lua from Atlas-CFM's set pages and DmorphOcto's item slots. Do not edit.",
  "-- Versions of the same tier set piece (quest upgrades): a member wearing any of them gets the paid lines",
  "-- of the one that dropped. One group per line: item ids, then what they are.",
  "sepgp_lootvariants = {" }
local groups = 0
-- only the class tier pages (T0 .. T3.5, AQ40): other pages (world drops,
-- tabards, crafted weapons) list different items that only share a slot
local function TierPage(p)
  return string.find(p, "^T%d+%u") or string.find(p, "^AQ40%u")
end
for _, p in ipairs(order) do
  if not TierPage(p) then pages[p].ids = {} end
  local bySlot, slots = {}, {}
  for _, e in ipairs(pages[p].ids) do
    local s = slot[e[1]]
    if s then
      if not bySlot[s] then bySlot[s] = {} table.insert(slots, s) end
      table.insert(bySlot[s], e)
    end
  end
  table.sort(slots)
  for _, s in ipairs(slots) do
    local g = bySlot[s]
    if table.getn(g) >= 2 then
      local ids, names = {}, {}
      for _, e in ipairs(g) do table.insert(ids, e[1]) table.insert(names, e[2]) end
      table.insert(out, "  { " .. table.concat(ids, ", ") .. " }, -- " .. p .. " " .. (SLOTNAME[s] or s) .. ": " .. table.concat(names, " / "))
      groups = groups + 1
    end
  end
end
table.insert(out, "}")
local f = io.open(OUT, "w")
f:write(table.concat(out, "\n") .. "\n")
f:close()
print(groups .. " groups written to " .. OUT)
