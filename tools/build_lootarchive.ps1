# Builds loot_archive.lua (sepgp_lootarchive: what each member paid GP for,
# before the addon's own loot history) from the guild website's database dump.
# 18 Nov 2026: the site's host stopped; its handover backup (ERROR-backup.zip)
# has server\db\errorguild.sql.gz with the epgp_loot table (22 Jul - 25 Oct 2026).
#   powershell -ExecutionPolicy Bypass -File tools\build_lootarchive.ps1 -Sql <errorguild.sql or .sql.gz>
# Only paid rows are kept (Mainspec GP / Offspec GP), charged to gp_player.
# Times: the table's synced_at, which is UTC (matches the addon's history).
param(
  [Parameter(Mandatory = $true)][string]$Sql,
  [string]$Out
)
$ErrorActionPreference = "Stop"
if (-not $Out) { $Out = Join-Path (Split-Path -Parent $MyInvocation.MyCommand.Path) "..\loot_archive.lua" }

function Open-Dump($path) {
  $fs = [System.IO.File]::OpenRead((Resolve-Path $path))
  if ($path -like "*.gz") { $fs = New-Object System.IO.Compression.GZipStream($fs, [System.IO.Compression.CompressionMode]::Decompress) }
  return New-Object System.IO.StreamReader($fs, [System.Text.Encoding]::UTF8)
}
function Unq($s) {
  if ($s -eq "NULL") { return $null }
  $s = $s.Substring(1, $s.Length - 2)
  return ($s -replace "\\(.)", '$1')
}
function LuaStr($s) { return '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

$S = "'(?:[^'\\]|\\.)*'"
$lootRe = [regex]("\((\d+),($S),(\d+),($S),(-?\d+),(-?\d+),(-?\d+),(NULL|$S),$S,\d+,($S),($S),(?:NULL|\d+),(?:NULL|\d+),($S),(NULL|$S),'[0-9a-f]+'\)")
$metaRe = [regex]("[(]\s*(\d+),($S),\d+,$S,")

$rows = New-Object System.Collections.ArrayList
$names = @{}
$r = Open-Dump $Sql
try {
  while ($null -ne ($line = $r.ReadLine())) {
    if ($line.StartsWith('INSERT INTO `epgp_loot` VALUES')) {
      foreach ($m in $lootRe.Matches($line)) {
        $action = Unq $m.Groups[4].Value
        if ($action -ne "Mainspec GP" -and $action -ne "Offspec GP") { continue }
        $who = Unq $m.Groups[8].Value
        if (-not $who) { $who = Unq $m.Groups[2].Value }
        $synced = Unq $m.Groups[12].Value
        if (-not $synced) { continue }
        $dt = [datetime]::ParseExact($synced, "yyyy-MM-dd HH:mm:ss", [Globalization.CultureInfo]::InvariantCulture)
        $t = ([DateTimeOffset]::new($dt, [TimeSpan]::Zero)).ToUnixTimeSeconds()
        [void]$rows.Add([pscustomobject]@{ who = $who; t = $t; id = [int]$m.Groups[3].Value; a = $action; gp = [int]$m.Groups[7].Value })
      }
    } elseif ($line.StartsWith('INSERT INTO `item_meta` VALUES')) {
      foreach ($m in $metaRe.Matches($line)) { $names[[int]$m.Groups[1].Value] = Unq $m.Groups[2].Value }
    }
  }
} finally { $r.Close() }
if ($rows.Count -eq 0) { throw "no paid rows found in epgp_loot" }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- Generated by tools/build_lootarchive.ps1 from the guild website's database (epgp_loot). Do not edit.")
[void]$sb.AppendLine("-- What each member paid GP for before the addon's own loot history; read by ui\PaidLoot.lua.")
[void]$sb.AppendLine("-- Per member: { time (UTC), item id, item name, action, GP }")
[void]$sb.AppendLine("sepgp_lootarchive = {")
foreach ($g in ($rows | Group-Object who | Sort-Object Name)) {
  [void]$sb.AppendLine("  [" + (LuaStr $g.Name) + "] = {")
  foreach ($x in ($g.Group | Sort-Object t)) {
    $nm = $names[$x.id]; if (-not $nm) { $nm = "" }
    [void]$sb.AppendLine("    { $($x.t), $($x.id), $(LuaStr $nm), $(LuaStr $x.a), $($x.gp) },")
  }
  [void]$sb.AppendLine("  },")
}
[void]$sb.AppendLine("}")
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($Out), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
$noName = @($rows | Where-Object { -not $names[$_.id] }).Count
Write-Host ("{0} paid rows for {1} members written to {2} ({3} without an item name)" -f $rows.Count, @($rows | Group-Object who).Count, $Out, $noName)
